// Copies shared/*.js into bot/src/shared and web/lib/shared (the website deploys on its own, so it cannot
// import from outside its folder). `--check` only verifies the copies are identical and exits 1 if not.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'shared');
const targets = [join(root, 'bot', 'src', 'shared'), join(root, 'web', 'lib', 'shared')];
const HEADER = '// GENERATED COPY - edit /shared and run "node scripts/sync-shared.js". Do not edit this file.\n';

// git may check files out with CRLF on Windows; compare with line endings normalised so that is not a "difference"
const lf = (text) => text.replace(/\r\n/g, '\n');
const sharedFiles = () => readdirSync(source).filter((f) => f.endsWith('.js'));
const expected = (name) => HEADER + lf(readFileSync(join(source, name), 'utf8'));

/** @returns list of problems (empty = in sync) */
export function checkSync() {
  const problems = [];
  for (const dir of targets) {
    for (const name of sharedFiles()) {
      const file = join(dir, name);
      if (!existsSync(file)) problems.push(`missing ${file}`);
      else if (lf(readFileSync(file, 'utf8')) !== expected(name)) problems.push(`out of date ${file}`);
    }
  }
  return problems;
}

export function sync() {
  for (const dir of targets) {
    mkdirSync(dir, { recursive: true });
    for (const name of sharedFiles()) writeFileSync(join(dir, name), expected(name), 'utf8');
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const problems = checkSync();
    if (problems.length) {
      console.error(problems.join('\n'));
      process.exit(1);
    }
    console.log('shared copies are in sync');
  } else {
    sync();
    console.log(`synced ${sharedFiles().length} shared file(s) into ${targets.length} places`);
  }
}
